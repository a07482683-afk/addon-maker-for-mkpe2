# -*- coding: utf-8 -*-
"""Best-effort converter from common legacy ModPE patterns to Bedrock Script API.

This is a source translator, not a full JavaScript transpiler. Unsupported legacy
APIs are preserved as comments and listed for manual migration.
"""
import json
import re
from pathlib import Path

from PySide2 import QtWidgets


SERVER_API_VERSION = "1.13.0"

HEADER = """// Generated by Addon Maker — ModPE → Bedrock Script API
// Review the migration report before using this script in Minecraft.
// Legacy ModPE APIs cannot all be translated: custom items/blocks must be
// declared in BP JSON; they cannot be registered dynamically by Script API.
import { world, system, ItemStack } from "@minecraft/server";

"""

def _convert_source(source):
    output = []
    warnings = []
    # Translate simple top-level ModPE callbacks to modern event subscriptions.
    source = re.sub(r"\bfunction\s+newLevel\s*\(\s*\)\s*\{",
                    "world.afterEvents.worldLoad.subscribe((event) => {", source)
    source = re.sub(r"\bfunction\s+leaveGame\s*\(\s*\)\s*\{",
                    "// leaveGame has no direct Script API equivalent; cleanup manually.\nfunction legacyLeaveGame() {", source)
    source = re.sub(r"\bfunction\s+useItem\s*\(\s*x\s*,\s*y\s*,\s*z\s*,\s*itemId\s*,\s*blockId\s*,\s*side\s*\)\s*\{",
                    "world.afterEvents.itemUseOn.subscribe((event) => {\n    const { source: player, itemStack } = event;\n    const itemId = itemStack ? itemStack.typeId : \"\";\n    const block = event.block;\n    const x = block.location.x, y = block.location.y, z = block.location.z;\n    const blockId = block.typeId;\n    const side = event.blockFace;", source)
    source = re.sub(r"\bfunction\s+procCmd\s*\(\s*command\s*\)\s*\{",
                    "world.beforeEvents.chatSend.subscribe((event) => {\n    const command = event.message.replace(/^\\//, \"\");", source)

    # Safe, direct API substitutions.
    source = re.sub(r"\bclientMessage\s*\(", "world.sendMessage(", source)
    source = re.sub(r"\bPlayer\.getX\s*\(\s*\)", "player.location.x", source)
    source = re.sub(r"\bPlayer\.getY\s*\(\s*\)", "player.location.y", source)
    source = re.sub(r"\bPlayer\.getZ\s*\(\s*\)", "player.location.z", source)
    source = re.sub(r"\bPlayer\.addItemCreativeInv\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)",
                    "/* TODO: add a JSON item and creative-group entry for legacy numeric ID \\1 (amount \\2). */", source)
    source = re.sub(r"\bEntity\.setNameTag\s*\(\s*([A-Za-z_$][\w$]*)\s*,\s*([^)]+)\)",
                    "/* TODO: name-tag API migration required for entity \\1: \\2 */", source)

    # Calls which require declarative JSON content, not runtime Script API.
    declarative = [
        (r"\bModPE\.setItem\s*\(", "ModPE.setItem: define a custom item in BP/items/*.json and RP/textures."),
        (r"\bBlock\.defineBlock\s*\(", "Block.defineBlock: define a custom block in BP/blocks/*.json and RP."),
        (r"\bBlock\.setDestroyTime\s*\(", "Block.setDestroyTime: move destroy time into the block JSON components."),
        (r"\bBlock\.setExplosionResistance\s*\(", "Block.setExplosionResistance: move resistance into block JSON components."),
        (r"\bLevel\.addShapedRecipe\s*\(", "Level.addShapedRecipe: create a crafting recipe JSON in BP/recipes/."),
        (r"\bEntity\.spawnMob\s*\(", "Entity.spawnMob: use dimension.spawnEntity with a namespaced entity identifier."),
    ]
    for pattern, message in declarative:
        if re.search(pattern, source):
            warnings.append(message)
            source = re.sub(pattern, "/* UNSUPPORTED LEGACY API — " + message + " */ (", source)

    if "world.beforeEvents.chatSend" in source:
        warnings.append("Команды procCmd перенесены на chatSend; проверьте event.cancel и обработку префикса команды.")
    if "world.afterEvents.worldLoad" in source:
        warnings.append("newLevel перенесён на worldLoad; проверьте поведение в целевой версии Script API.")
    if "player.location" in source and "const player" not in source and "source: player" not in source:
        warnings.append("Player.getX/Y/Z заменены на player.location; переменная player должна существовать в обработчике.")

    # Report remaining legacy identifiers rather than silently emitting false conversions.
    for token in ("ModPE.", "Block.", "Level.", "Player.", "Entity.", "clientMessage", "procCmd", "useItem", "newLevel"):
        if re.search(r"\b" + re.escape(token), source):
            warnings.append("Остался необработанный legacy-вызов: " + token)
    return source, warnings


def convert_modpe_project(project_folder, api_version=SERVER_API_VERSION):
    project = Path(project_folder)
    bp = project / "BP"
    manifest_path = bp / "manifest.json"
    if not manifest_path.is_file():
        raise ValueError("В проекте нет BP/manifest.json.")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8-sig"))
    modules = manifest.setdefault("modules", [])
    if not any(isinstance(m, dict) and m.get("type") == "script" for m in modules):
        modules.append({
            "type": "script",
            "language": "javascript",
            "uuid": "7a2b9e31-4f68-4a4c-aed1-5d7b2f0c9137",
            "version": [1, 0, 0],
            "entry": "scripts/main.js"
        })
    dependencies = manifest.setdefault("dependencies", [])
    dependencies[:] = [d for d in dependencies if not (isinstance(d, dict) and d.get("module_name") == "@minecraft/server")]
    dependencies.append({"module_name": "@minecraft/server", "version": api_version})
    scripts_dir = bp / "scripts"
    scripts_dir.mkdir(parents=True, exist_ok=True)

    legacy_dir = project / "ModPE"
    files = sorted(legacy_dir.rglob("*.js")) if legacy_dir.is_dir() else []
    if not files:
        raise ValueError("В папке ModPE нет .js файлов для преобразования.")
    converted = []
    reports = []
    for file_path in files:
        raw = file_path.read_text(encoding="utf-8-sig")
        code, warnings = _convert_source(raw)
        converted.append("// Source: " + file_path.name + "\n" + code)
        reports.append({"file": file_path.name, "warnings": warnings})
    (scripts_dir / "main.js").write_text(HEADER + "\n\n".join(converted), encoding="utf-8")
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    report_path = project / "ModPE" / "conversion-report.json"
    report_path.write_text(json.dumps({
        "target": "Bedrock Script API",
        "module": "@minecraft/server",
        "api_version": api_version,
        "sources": reports,
        "output": "BP/scripts/main.js"
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return {"output": scripts_dir / "main.js", "files": len(files), "reports": reports}


class ModPEConverterDialog(QtWidgets.QDialog):
    def __init__(self, project_path, parent=None):
        super().__init__(parent)
        self.project = Path(project_path)
        self.setWindowTitle("Преобразование ModPE → Bedrock Script API")
        self.resize(760, 560)
        layout = QtWidgets.QVBoxLayout(self)
        info = QtWidgets.QLabel(
            "Конвертер переносит распространённые вызовы и события в @minecraft/server. "
            "Это не автоматический перевод любого JavaScript: регистрация предметов, блоков "
            "и рецептов переносится в JSON-файлы, а неподдерживаемый код попадёт в отчёт."
        )
        info.setWordWrap(True)
        layout.addWidget(info)
        form = QtWidgets.QFormLayout()
        self.api_version = QtWidgets.QComboBox()
        self.api_version.addItems(["1.13.0", "1.12.0", "1.11.0", "1.10.0"])
        self.api_version.setCurrentText(SERVER_API_VERSION)
        form.addRow("Версия @minecraft/server:", self.api_version)
        layout.addLayout(form)
        self.status = QtWidgets.QLabel("Исходные файлы берутся из папки проекта ModPE/*.js.")
        self.status.setWordWrap(True)
        layout.addWidget(self.status)
        self.report = QtWidgets.QPlainTextEdit()
        self.report.setReadOnly(True)
        layout.addWidget(self.report, 1)
        row = QtWidgets.QHBoxLayout()
        run = QtWidgets.QPushButton("Преобразовать в BP/scripts/main.js")
        run.clicked.connect(self.run_conversion)
        close = QtWidgets.QPushButton("Закрыть")
        close.clicked.connect(self.close)
        row.addWidget(run)
        row.addWidget(close)
        layout.addLayout(row)

    def run_conversion(self):
        try:
            result = convert_modpe_project(self.project, self.api_version.currentText())
            lines = ["Создано: " + str(result["output"]), "Обработано файлов: " + str(result["files"]), ""]
            for report in result["reports"]:
                lines.append("Файл: " + report["file"])
                if report["warnings"]:
                    lines.extend("  • " + item for item in report["warnings"])
                else:
                    lines.append("  • Явных неподдерживаемых конструкций не обнаружено.")
            lines.extend(["", "Важно: открой BP/manifest.json и BP/scripts/main.js, затем проверь скрипт в Minecraft."])
            self.report.setPlainText("\n".join(lines))
            self.status.setText("Преобразование завершено. Отчёт сохранён в ModPE/conversion-report.json.")
        except Exception as exc:
            QtWidgets.QMessageBox.critical(self, "Ошибка преобразования", str(exc))
